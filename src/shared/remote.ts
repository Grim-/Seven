import type { EngineRequestName, EngineRequests, EventName, MainRequestName } from './protocol'
import type { DeviceLevelId } from './types'

export type RemoteLevelId = DeviceLevelId | 'never'

export interface RemoteLevel {
  id: DeviceLevelId
  rank: number
  label: string
  description: string
}

export const REMOTE_LEVELS: RemoteLevel[] = [
  { id: 'chat', rank: 1, label: 'Chat', description: 'Talk to Seven and read what it knows.' },
  { id: 'full', rank: 2, label: 'Full', description: 'Normal use: everything Chat can, plus changing content.' },
  { id: 'admin', rank: 3, label: 'Admin', description: 'Everything, including settings, installs, tools that act on this PC, and unlocking the vault.' }
]

export type MainRemote = DeviceLevelId | 'device' | 'hidden'

export function remoteRank(level: RemoteLevelId): number {
  return REMOTE_LEVELS.find((l) => l.id === level)?.rank ?? Number.POSITIVE_INFINITY
}

export function remoteAllows(device: DeviceLevelId, needed: RemoteLevelId | MainRemote | undefined): boolean {
  if (!needed || needed === 'never' || needed === 'hidden' || needed === 'device') return false
  return remoteRank(device) >= remoteRank(needed)
}

